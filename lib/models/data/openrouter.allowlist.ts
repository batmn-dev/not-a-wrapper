import type { ModelConfig } from "../types"

/**
 * Curated OpenRouter allowlist — the EDITORIAL half of the generated catalog.
 *
 * `scripts/generate-openrouter-catalog.ts` joins this list with the committed
 * `openrouter.snapshot.json` (the MACHINE half: pricing, context, capability
 * parameters, listing existence) and emits `openrouter.generated.ts`. Facts
 * that rot live in the snapshot; anything a human should word or rank lives
 * here. Refresh: `bun run catalog:openrouter:refresh`.
 *
 * Curation policy (ADR-0022): expose the broad reference chat catalog when a
 * live OpenRouter route exists and the model fits the app's language-model
 * runtime. Anything delisted at snapshot time gets removed here plus a
 * succession entry in `lib/models/model-id-migration.ts`.
 *
 * Deliberately excluded:
 * - `anthropic/*-fast` variants (2× price for the same models).
 * - Batch, provider-specialized, and duplicate fast variants.
 * - `openrouter/auto|free|fusion` router pseudo-models (variable-pricing
 *   sentinel `-1000000`).
 * - Image/audio/video OUTPUT models (Nano Banana, Lyria, Imagine, GPT-Image,
 *   TTS/Live); multimodal language models with image input remain supported.
 * - `minimax/minimax-m2-her` (no tools, 2k maxOut).
 */
export type OpenRouterAllowlistEntry = {
  /** Bare OpenRouter slug (the generated id is `openrouter:` + slug). */
  slug: string
  /** Authoritative full user-facing model name. */
  name: string
  /** Optional compact label for constrained presentation surfaces. */
  shortName?: string
  description: string
  tags: string[]
  modelFamily: string
  /** Explicit recommendation lane for successor-aware classification. */
  lineageId?: ModelConfig["lineageId"]
  /** Defaults to stable; previews cannot supersede stable predecessors. */
  releaseStage?: NonNullable<ModelConfig["releaseStage"]>
  /** Dated editorial route lifecycle evidence. */
  lifecycle?: ModelConfig["lifecycle"]
  /**
   * Real underlying vendor id. This open-set value does not control icon
   * lookup: the generator copies `entry.icon` to `model.icon`, which callers
   * pass to `getVendorIcon`. Use "openrouter" for `icon` when the vendor has
   * no registered icon.
   */
  baseProviderId: string
  /** Vendor-registry icon key; "openrouter" when the vendor has no own icon. */
  icon: string
  /**
   * Explicit logical-model mapping (ADR-0020): the DIRECT catalog id this
   * wrapped entry is a second route to. The generator copies it onto the
   * generated record; the logical catalog then compiles both into one
   * selector model. Leave absent for OpenRouter-only models (they compile
   * into their own logical model). `:free` pool entries stay unmapped even
   * when a paid sibling exists — the free pool is a distinct serving tier.
   */
  logicalModelId?: string
  speed: NonNullable<ModelConfig["speed"]>
  intelligence: NonNullable<ModelConfig["intelligence"]>
  openSource: boolean
  /** Overrides the snapshot-derived listing date (`created`) when set. */
  releasedAt?: string
  /** Explicit upstream snapshot date; never inferred from the display name. */
  snapshotDate?: string
  modelPage?: string
  /**
   * Opt OUT of reasoning config even when the live `supported_parameters`
   * include `reasoning`. The generator can never opt IN without the live
   * parameter — reasoning support is a machine fact, not an editorial one.
   */
  reasoningOptOut?: boolean
}

type ReferenceCatalogEntry = Omit<OpenRouterAllowlistEntry, "description"> & {
  maker: string
}

/**
 * Keep the broad T3-compatible additions compact without weakening the
 * generator contract: ids, model families, vendor identity, and editorial
 * capability tags remain explicit, while the repeated route description is
 * derived in one place. Machine facts still come exclusively from the live
 * OpenRouter snapshot.
 */
function referenceCatalogModel({
  maker,
  ...entry
}: ReferenceCatalogEntry): OpenRouterAllowlistEntry {
  return {
    ...entry,
    description: `${entry.name} by ${maker}, served through OpenRouter.`,
  }
}

